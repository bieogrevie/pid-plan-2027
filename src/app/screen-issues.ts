const days = (a: string, b: string) => Math.round((Date.parse(b) - Date.parse(a)) / 864e5);
const durations = screenIssues.filter(s => s.issueDate && s.doneDate).map(s => days(s.issueDate!, s.doneDate!)).sort((a, b) => a - b);

